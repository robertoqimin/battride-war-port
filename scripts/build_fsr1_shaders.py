#!/usr/bin/env python3
"""Compile shaders/fsr1.comp (EASU and RCAS) to SPIR-V and write fsr1_spv.h.

The generated header is committed, so neither the game build nor the
AppImage needs a shader compiler. Rerun after changing the shader or the
vendored FSR headers: python3 scripts/build_fsr1_shaders.py
Requires glslangValidator and spirv-val (Fedora: glslang, spirv-tools).
"""
import hashlib
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'shaders/fsr1.comp'
OUTPUT = ROOT / 'fsr1_spv.h'


def compile_pass(define, work):
    out = work / (define + '.spv')
    subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.0', '-D' + define,
                    '-S', 'comp', '-o', str(out), str(SOURCE)], check=True, stdout=subprocess.DEVNULL)
    subprocess.run(['spirv-val', '--target-env', 'vulkan1.0', str(out)], check=True)
    return out.read_bytes()


def c_array(name, data):
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    lines = ['static const uint32_t %s[%d] = {' % (name, len(words))]
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    inputs = [SOURCE, ROOT / 'third_party/fsr1/ffx_a.h', ROOT / 'third_party/fsr1/ffx_fsr1.h']
    stamp = ', '.join('%s %s' % (p.relative_to(ROOT), hashlib.sha256(p.read_bytes()).hexdigest()[:16])
                      for p in inputs)
    with tempfile.TemporaryDirectory() as work:
        easu = compile_pass('FSR1_EASU', Path(work))
        rcas = compile_pass('FSR1_RCAS', Path(work))
    OUTPUT.write_text('/* Generated by scripts/build_fsr1_shaders.py from %s; do not edit.\n'
                      ' * AMD FidelityFX Super Resolution 1.0, MIT (third_party/fsr1/LICENSE.txt). */\n'
                      '#pragma once\n#include <stdint.h>\n\n%s\n\n%s\n'
                      % (stamp, c_array('fsr1_easu_spv', easu), c_array('fsr1_rcas_spv', rcas)))
    print('Wrote', OUTPUT.relative_to(ROOT), '(EASU %d bytes, RCAS %d bytes)' % (len(easu), len(rcas)))


if __name__ == '__main__':
    main()
